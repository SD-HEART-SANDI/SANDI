import pytest

from system.models.documents import Document, DocumentPage, TextChunk
from system.rag.chunking import chunk_document


@pytest.fixture
def sample_document():
    """Create a synthetic three-page document."""
    return Document(
        id="CF-001",
        title="CalFresh Eligibility Guide",
        organization="Test Agency",
        published_year=2026,
        source_url=None,
        pages=(
            DocumentPage(
                page_number=1,
                text="CalFresh provides food assistance."
            ),
            DocumentPage(
                page_number=2,
                text="Applicants may need to verify identity."
            ),
            DocumentPage(
                page_number=3,
                text="Household income may affect eligibility."
            ),
        )
    )


def test_returns_tuple(sample_document):
    chunks = chunk_document(sample_document)

    assert isinstance(chunks, tuple)


def test_one_chunk_per_page(sample_document):
    chunks = chunk_document(sample_document)

    assert len(chunks) == 3
    assert all(isinstance(chunk, TextChunk) for chunk in chunks)


def test_preserves_source_metadata(sample_document):
    chunks = chunk_document(sample_document)

    assert all(chunk.document_id == "CF-001" for chunk in chunks)
    assert [chunk.page_number for chunk in chunks] == [1, 2, 3]


def test_preserves_text(sample_document):
    chunks = chunk_document(sample_document)

    for chunk, page in zip(chunks, sample_document.pages):
        assert chunk.text == page.text


def test_unique_reproducible_ids(sample_document):
    first_run = chunk_document(sample_document)
    second_run = chunk_document(sample_document)

    first_ids = [chunk.id for chunk in first_run]
    second_ids = [chunk.id for chunk in second_run]

    assert len(first_ids) == len(set(first_ids))
    assert first_ids == second_ids


def test_skips_empty_pages():
    document = Document(
        id="TEST-EMPTY",
        title="Empty Page Test",
        organization="Test Agency",
        published_year=None,
        source_url=None,
        pages=(
            DocumentPage(page_number=1, text="Valid content."),
            DocumentPage(page_number=2, text="   \n   "),
            DocumentPage(page_number=3, text="More content."),
        )
    )

    chunks = chunk_document(document)

    assert len(chunks) == 2
    assert [chunk.page_number for chunk in chunks] == [1, 3]
    assert all(chunk.text.strip() for chunk in chunks)
